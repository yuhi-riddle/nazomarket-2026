import { describe, expect, it } from "vitest";
import { limitedKinds } from "./limitedKinds.ts";

const kinds = (limited: string | null, price: number | null = null, priceNote: string | null = null) =>
  limitedKinds({ limited, price, priceNote });

describe("limitedKinds", () => {
  it("数に限りがあるものは数量限定", () => {
    for (const text of [
      "各日30部", "限定300部", "限定300個", "限定40部", "限定50着", "数量限定販売", "数量限定で再販", "数量限定（売り切り）",
      "数量限定(両日再販)", "両日とも各色200羽ずつ", "限定100個（なくなり次第受注販売、送料300円別）",
      "数量限定(各日150部。ナゾマ以降の再販等は未定)", "数量限定（完全書き下ろし・以降の販売は未定）",
    ]) {
      expect(kinds(text), text).toEqual(["数量限定"]);
    }
  });

  it("この会場でしか買えないものは会場限定", () => {
    for (const text of [
      "ナゾトキマーケット限定", "ナゾトキマーケット限定販売", "会場限定(公式ブースで2日間のみ販売)", "会場2日間限定・再販なし",
      "会場限定販売・通販なし", "ナゾトキマーケットでしか買えない限定セット",
    ]) {
      expect(kinds(text), text).toEqual(["会場限定"]);
    }
  });

  it("後日ほかでも買えるが先に買えるものは先行販売", () => {
    for (const text of [
      "先行販売", "ナゾトキマーケット2026 最速先行販売", "最速先行販売(ナゾトキマーケット2026)", "限定先行発売",
      "先行販売(2026年11月発売予定)。取り置き予約は予定数量に達し次第締切", "先行販売(ナゾマで先行販売と告知)",
      "ナゾトキマーケット先行販売(一般発売は2026年11月13日)", "ナゾトキマーケット2026で新発売（通販は後日開始予定）",
    ]) {
      expect(kinds(text), text).toEqual(["先行販売"]);
    }
  });

  it("値段だけが限られるものは限定価格で、会場限定にはしない", () => {
    for (const text of [
      "会場限定価格", "ナゾトキマーケット会場限定価格", "ナゾトキマーケット限定価格", "ナゾマ限定価格", "初回限定価格",
      "ナゾトキマーケットでの特別割引価格（1,000円）", "ナゾトキマーケット限定価格（1,000円）",
    ]) {
      expect(kinds(text), text).toEqual(["限定価格"]);
    }
  });

  it("買える人が決まっているものは購入条件あり", () => {
    for (const text of ["謎を解いた人だけ購入可", "過去に『FLAG』に参加した人限定の販売", "抽選に当選した方のみ購入可（先着順・売り切れの場合あり）"]) {
      expect(kinds(text), text).toEqual(["購入条件あり"]);
    }
  });

  it("複数に当てはまるものは全部返し、順番はそろえる", () => {
    expect(kinds("先行販売・各日数量限定（一般発売は2026-12-08）")).toEqual(["数量限定", "先行販売"]);
    expect(kinds("ナゾマ現地引換の先行予約チケット(7日・8日 各50個)、オンライン先行100個")).toEqual(["数量限定", "先行販売"]);
    expect(kinds("ナゾトキマーケット会場限定先行販売(一般発売は2026年11月19日)")).toEqual(["会場限定", "先行販売"]);
    expect(kinds("ナゾトキマーケットでの先行発売（特別価格）")).toEqual(["先行販売", "限定価格"]);
    expect(kinds("ナゾトキマーケット2026で先行販売（先行販売限定価格）")).toEqual(["先行販売", "限定価格"]);
    expect(kinds("ナゾトキマーケット限定（2作同時購入時のみ）")).toEqual(["会場限定", "購入条件あり"]);
    expect(kinds("特装版（5,000円）は数量限定。ここでしか手に入らない謎付きトートバッグ付き")).toEqual(["数量限定", "会場限定"]);
  });

  it("限定とは言えないものには付けない", () => {
    for (const text of [
      null,
      "事前予約フォームあり（受付11/7 18:00まで）",
      "事前予約フォームあり（10/29 の告知）",
      "事前予約制。10/27 に予約数に達したため予約受付を終了（在庫が少ない）",
      "後日購入者限定コンテンツ付き",
      "ナゾトキマーケット会場価格",
      "2026秋M3での先行販売後、残部をナゾトキマーケット2026で頒布。売り切れ次第この形式での販売を終了",
    ]) {
      expect(kinds(text), String(text)).toEqual([]);
    }
  });

  it("価格の補足からも限定価格と先行販売を拾う（カードの表示と同じ判定）", () => {
    expect(kinds(null, 2000, "ナゾマ限定価格（通常2,200円）")).toEqual(["限定価格"]);
    expect(kinds(null, 1400, "ナゾトキマーケット会場価格（通常1,600円）")).toEqual(["限定価格"]);
    expect(kinds(null, 1200, "ナゾトキマーケット先行販売価格（一般販売1,500円）")).toEqual(["先行販売"]);
    expect(kinds(null, 1500, "M3先行販売価格は1,500円、一般販売価格2,000円")).toEqual([]);
    expect(kinds("先行販売", 1200, "ナゾトキマーケット先行販売価格（一般販売1,500円）")).toEqual(["先行販売"]);
  });

  it("価格の記述があっても会場限定の販売を落とさない", () => {
    expect(kinds("会場限定販売・特別価格")).toEqual(["会場限定", "限定価格"]);
    expect(kinds("会場限定価格")).toEqual(["限定価格"]);
  });

  it("同時購入の冊数は数量限定と数えない", () => {
    expect(kinds("2冊同時購入時のみ")).toEqual(["購入条件あり"]);
  });

  it("先行販売の価格補足に書かれた限定価格も拾う", () => {
    expect(kinds(null, 1000, "先行販売限定価格")).toEqual(["先行販売", "限定価格"]);
    expect(kinds("先行販売", 6500, "会場限定価格(通常6,600円→6,500円)")).toEqual(["先行販売", "限定価格"]);
  });
});
